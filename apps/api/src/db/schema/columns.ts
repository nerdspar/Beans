import { sql } from 'drizzle-orm'
import { customType, pgPolicy, timestamp, uuid } from 'drizzle-orm/pg-core'

/**
 * Shared column builders and policy helpers.
 *
 * Everything version-fragile about our Drizzle usage is deliberately concentrated here, so an
 * upgrade touches one file rather than twenty.
 */

/**
 * `bytea`, for every encrypted column.
 *
 * Drizzle 0.45.2 has no first-class `bytea` — it lands in v1. Keeping it here as a `customType`
 * means adopting the native type later is a one-line change rather than a schema-wide edit.
 *
 * No `toDriver`/`fromDriver` is needed: node-postgres already maps `bytea` to `Buffer` both ways.
 */
export const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType() {
    return 'bytea'
  },
})

/** Primary key used by every table. Random UUIDs, generated by the database. */
export const primaryId = () => uuid('id').primaryKey().defaultRandom()

/**
 * The tenancy column. Present on every household-scoped table, denormalized deliberately so RLS
 * and indexes can act on it directly without a join (ARCHITECTURE.md §6).
 */
export const householdId = () => uuid('household_id').notNull()

export const createdAt = () =>
  timestamp('created_at', { withTimezone: true }).notNull().defaultNow()

/**
 * The delta-sync cursor column (ARCHITECTURE.md §7.3).
 *
 * Maintained by a **database trigger**, not application code — see the `set_updated_at` trigger in
 * the custom migration. If it were set in the repository layer, one forgotten write path would
 * silently desynchronize every client, and the symptom would be missing data rather than an error.
 *
 * Any new table that the client caches needs this column *and* its trigger, added together.
 */
export const updatedAt = () =>
  timestamp('updated_at', { withTimezone: true }).notNull().defaultNow()

/**
 * Row-level security: isolation layer 2 (layer 1 is the repository layer requiring a household
 * context on every call). The redundancy is deliberate.
 *
 * `current_setting(..., true)` returns NULL when the GUC is unset, and `household_id = NULL` is
 * NULL rather than true — so a request that forgot to set the session variable sees **nothing**.
 * Failing closed is the entire point.
 *
 * The `nullif(..., '')` is load-bearing, not defensive noise. Once a custom GUC has been set on a
 * connection, ending the transaction reverts it to the **empty string** rather than unsetting it.
 * On a pooled connection that previously served a request, `current_setting` therefore returns
 * `''`, and `''::uuid` raises `invalid input syntax for type uuid` instead of comparing. That
 * still doesn't leak data, but it fails with an error rather than an empty result — a guarantee
 * resting on an exception is a far worse guarantee. `nullif` turns it back into a clean NULL.
 * Caught by the tenant isolation integration test, which is exactly what that suite is for.
 *
 * This only protects us if the application connects as a **non-superuser, non-`BYPASSRLS` role**.
 * Postgres silently ignores RLS for superusers and table owners, which would disable this layer
 * with no visible symptom.
 */
export const householdIsolationPolicy = (tableName: string) =>
  pgPolicy(`${tableName}_household_isolation`, {
    as: 'permissive',
    for: 'all',
    to: 'public',
    using: sql`household_id = nullif(current_setting('app.current_household', true), '')::uuid`,
    withCheck: sql`household_id = nullif(current_setting('app.current_household', true), '')::uuid`,
  })

/**
 * The `households` table itself, whose tenancy column is `id` rather than `household_id`.
 * Same semantics, same fail-closed behavior.
 */
export const householdSelfIsolationPolicy = () =>
  pgPolicy('households_self_isolation', {
    as: 'permissive',
    for: 'all',
    to: 'public',
    using: sql`id = nullif(current_setting('app.current_household', true), '')::uuid`,
    withCheck: sql`id = nullif(current_setting('app.current_household', true), '')::uuid`,
  })

/** As above, but keyed to the acting user rather than the household. Used by `user_preferences`. */
export const userIsolationPolicy = (tableName: string) =>
  pgPolicy(`${tableName}_user_isolation`, {
    as: 'permissive',
    for: 'all',
    to: 'public',
    using: sql`user_id = nullif(current_setting('app.current_user_id', true), '')`,
    withCheck: sql`user_id = nullif(current_setting('app.current_user_id', true), '')`,
  })
